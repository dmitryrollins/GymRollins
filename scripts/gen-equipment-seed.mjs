#!/usr/bin/env node
// equipment-kinds.json and equipment-requirements.json (bundled in the app) -> a SQL migration, plus one generic
// catalogue item per kind. `--check` fails when the migration differs from what the JSON generates (the drift test).
import { createHash } from 'node:crypto'
import { readFileSync, writeFileSync } from 'node:fs'
import { resolve } from 'node:path'

const root = resolve(import.meta.dirname, '..')
const output = resolve(root, 'supabase/migrations/20261030000004_equipment_seed.sql')
/** `GymRepository.genericItemNamespace`: phone and server derive the same id for a kind's generic item. */
const genericItemNamespace = '6b1f3c2e-8d4a-5e17-9a60-2f4c7d9b1e35'

const q = (s) => `'${String(s).replaceAll("'", "''")}'`

/** The same bytes as GymCore's `StableUUID.make(namespace:name:)`. */
export function stableUUID(namespace, name) {
  const input = Buffer.concat([Buffer.from(namespace.replaceAll('-', ''), 'hex'), Buffer.from(name, 'utf8')])
  const bytes = createHash('sha256').update(input).digest().subarray(0, 16)
  bytes[6] = (bytes[6] & 0x0f) | 0x50
  bytes[8] = (bytes[8] & 0x3f) | 0x80
  const hex = bytes.toString('hex')
  return `${hex.slice(0, 8)}-${hex.slice(8, 12)}-${hex.slice(12, 16)}-${hex.slice(16, 20)}-${hex.slice(20)}`
}

export function seedSql(kinds, requirements) {
  const kindRows = kinds.map((k) => `(${q(k.id)},${q(k.name)},${q(k.category)},${q(k.load)})`)
  const itemRows = kinds.map((k) => `(${q(stableUUID(genericItemNamespace, k.id))},${q(k.id)})`)
  const requirementRows = Object.keys(requirements).sort()
    .map((id) => `(${q(id)},${q(JSON.stringify(requirements[id]))}::jsonb)`)
  return [
    '-- Generated by scripts/gen-equipment-seed.mjs from the JSON bundled in the app. Do not edit by hand.',
    `insert into public.equipment_kinds (id,name,category,load_type) values\n${kindRows.join(',\n')};`,
    `insert into public.equipment_items (id,kind_id) values\n${itemRows.join(',\n')};`,
    `insert into public.exercise_requirements (exercise_id,groups) values\n${requirementRows.join(',\n')};`,
    '',
  ].join('\n')
}

function generate() {
  const read = (name) => JSON.parse(readFileSync(resolve(root, 'ios/GymRollins/Resources', name), 'utf8'))
  return seedSql(read('equipment-kinds.json').kinds, read('equipment-requirements.json').requirements)
}

if (process.argv[1] === import.meta.filename) {
  const sql = generate()
  if (process.argv.includes('--check')) {
    if (readFileSync(output, 'utf8') !== sql) {
      console.error('The equipment seed differs from the bundled JSON: run scripts/gen-equipment-seed.mjs')
      process.exit(1)
    }
    console.log('Equipment seed matches the bundled JSON')
  } else {
    writeFileSync(output, sql)
    console.log(`Wrote ${output}`)
  }
}
